import assert from "node:assert/strict";
import { chromium } from "playwright";
const base = process.env.JOBSCOUT_TEST_URL || "http://127.0.0.1:3000";
const browser = await chromium.launch({ executablePath: process.env.JOBSCOUT_CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(base); await page.getByRole("heading", { name: /Un job qui vous ressemble/ }).waitFor();
  await page.screenshot({ path: process.env.JOBSCOUT_SCREENSHOT || "/workspace/scratch/jobscout-desktop.png", fullPage: true });
  await page.locator('input[type="file"]').setInputFiles({ name: "cv.txt", mimeType: "text/plain", buffer: Buffer.from("Camille Exemple. Expérience : développement de produits TypeScript et SQL. Formation : informatique.") });
  await page.getByRole("heading", { name: "Votre CV est prêt." }).waitFor();
  await page.getByRole("button", { name: "Ajouter une annonce" }).click();
  await page.getByLabel("Intitulé du poste").fill("Développeuse TypeScript");
  await page.getByLabel("Entreprise", { exact: true }).fill("Entreprise Exemple");
  await page.getByLabel("Lien de l'annonce").fill("https://example.org/job");
  await page.getByLabel("Description", { exact: true }).fill("Nous cherchons une développeuse TypeScript pour des interfaces accessibles.");
  await page.getByRole("button", { name: "Ajouter l'offre", exact: true }).click();
  await page.getByRole("button", { name: "Adapter mon CV avec ChatGPT", exact: true }).click();
  assert.match(await page.getByLabel("Consigne à copier dans ChatGPT").inputValue(), /Développeuse TypeScript/);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Mon profil", exact: true }).click();
  await page.getByLabel("Votre parcours").fill("Camille Exemple. Formation et expérience : développement TypeScript et SQL.");
  await page.getByRole("button", { name: "Continuer ma recherche" }).click();
  await page.getByRole("button", { name: "Adapter mon CV avec ChatGPT", exact: true }).click();
  assert.match(await page.getByLabel("Consigne à copier dans ChatGPT").inputValue(), /Camille Exemple/);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Mes documents", exact: true }).click();
  await page.getByLabel("Contenu JSON fourni par ChatGPT").fill(JSON.stringify({ cv: { identity: { full_name: "Camille Exemple" }, summary: "Développeuse TypeScript", sections: { experiences: [{ title: "Développeuse", company: "Entreprise Exemple", bullet_points: ["Création d'interfaces accessibles."] }] } } }));
  await page.getByRole("button", { name: "Importer mes documents" }).click();
  const download = page.waitForEvent("download"); await page.getByRole("button", { name: "CV PDF", exact: true }).click();
  assert.equal((await download).suggestedFilename(), "cv-adapte.pdf");
  await page.getByRole("button", { name: "Effacer mes données" }).click();
  await page.getByRole("button", { name: "Mon profil", exact: true }).click();
  assert.equal(await page.getByLabel("Votre parcours").inputValue(), "");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Explorer les offres" }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: "/workspace/scratch/jobscout-mobile.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("Browser smoke passed: manual offer, CV prompt, profile, document import and PDF download, erasure, responsive mobile, no JavaScript errors.");
} finally { await browser.close(); }
